use crate::Analysis;
use crate::analyzers::module_analyzer::visit_expansion;
use crate::errors::{SemanticError, SemanticResult};
use crate::semantics::{Symbol, SymbolInterface, Type};
use fpp_ast::{
    DefAliasType, DefArray, DefComponent, DefConstant, DefEnum, DefModule, DefModuleTemplate,
    DefStruct, SpecTemplateExpand, Visitor, Walkable,
};
use std::ops::ControlFlow;
use std::sync::Arc;

/// Check dictionary definitions
///
/// A dictionary constant must have a numeric, Boolean, string, or enum type, and
/// a dictionary type must be displayable. The dictionary definitions that pass
/// the check are recorded in `Analysis::dictionary_symbol_set`.
pub struct CheckDictionaryDefs;

impl CheckDictionaryDefs {
    pub fn check_constant_def(a: &mut Analysis, s: &Symbol) -> SemanticResult {
        if !s.is_dictionary_def() {
            return Ok(());
        }
        let id = s.node();
        let ok = match a.type_map.get(&id).map(|t| t.as_ref()) {
            Some(Type::String(_)) | Some(Type::Boolean) | Some(Type::Enum(_)) => true,
            // An alias type is neither an integer type nor a floating-point type
            Some(Type::Alias(_)) => false,
            Some(t) => t.is_numeric(),
            // The constant has no type when its value expression has none
            None => true,
        };
        if ok {
            a.dictionary_symbol_set.insert(s.clone());
            Ok(())
        } else {
            let loc = s.get_loc();
            let msg = "dictionary constant must have a numeric, Boolean, string, or enum type";
            Err(SemanticError::InvalidType {
                loc,
                msg: msg.to_string(),
                notes: vec![],
            })
        }
    }

    pub fn check_type_def(a: &mut Analysis, s: &Symbol) -> SemanticResult {
        if s.is_dictionary_def() {
            a.check_displayable_type(s.node(), s.get_loc(), "dictionary type is not displayable")?;
            a.dictionary_symbol_set.insert(s.clone());
        }
        Ok(())
    }
}

/// Emit the error of a check, if any
fn emit(result: SemanticResult) -> ControlFlow<()> {
    if let Err(err) = result {
        err.emit();
    }
    ControlFlow::Continue(())
}

impl<'ast> Visitor<'ast> for CheckDictionaryDefs {
    type Break = ();
    type State = Analysis;

    /// Analyze component members
    fn visit_def_component(
        &self,
        a: &mut Analysis,
        node: &'ast DefComponent,
    ) -> ControlFlow<Self::Break> {
        node.walk(a, self)
    }

    /// Visit module members
    fn visit_def_module(
        &self,
        a: &mut Analysis,
        node: &'ast DefModule,
    ) -> ControlFlow<Self::Break> {
        node.walk(a, self)
    }

    /// The members generated by a template expansion are members of the
    /// enclosing module, so analyze them here.
    fn visit_spec_template_expand(
        &self,
        a: &mut Self::State,
        node: &'ast SpecTemplateExpand,
    ) -> ControlFlow<Self::Break> {
        visit_expansion(self, a, node)
    }

    /// The body of a module template is analyzed where the template is expanded,
    /// not at the point of the definition.
    fn visit_def_module_template(
        &self,
        _a: &mut Self::State,
        _node: &'ast DefModuleTemplate,
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    fn visit_def_alias_type(
        &self,
        a: &mut Analysis,
        node: &'ast DefAliasType,
    ) -> ControlFlow<Self::Break> {
        let s = a
            .get_symbol(node)
            .unwrap_or_else(|| Symbol::AliasType(Arc::new(node.clone())));
        emit(Self::check_type_def(a, &s))
    }

    fn visit_def_array(&self, a: &mut Analysis, node: &'ast DefArray) -> ControlFlow<Self::Break> {
        let s = a
            .get_symbol(node)
            .unwrap_or_else(|| Symbol::ArrayType(Arc::new(node.clone())));
        emit(Self::check_type_def(a, &s))
    }

    fn visit_def_enum(&self, a: &mut Analysis, node: &'ast DefEnum) -> ControlFlow<Self::Break> {
        let s = a
            .get_symbol(node)
            .unwrap_or_else(|| Symbol::EnumType(Arc::new(node.clone())));
        emit(Self::check_type_def(a, &s))
    }

    fn visit_def_struct(
        &self,
        a: &mut Analysis,
        node: &'ast DefStruct,
    ) -> ControlFlow<Self::Break> {
        let s = a
            .get_symbol(node)
            .unwrap_or_else(|| Symbol::StructType(Arc::new(node.clone())));
        emit(Self::check_type_def(a, &s))
    }

    fn visit_def_constant(
        &self,
        a: &mut Analysis,
        node: &'ast DefConstant,
    ) -> ControlFlow<Self::Break> {
        let s = a
            .get_symbol(node)
            .unwrap_or_else(|| Symbol::Constant(Arc::new(node.clone())));
        emit(Self::check_constant_def(a, &s))
    }
}
