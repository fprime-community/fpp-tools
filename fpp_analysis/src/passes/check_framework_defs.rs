/// The checker for the framework definition named `name`, if there is one
fn lookup(table: &[(&str, Checker)], name: &str) -> Option<Checker> {
    table
        .iter()
        .find_map(|(n, checker)| (*n == name).then_some(*checker))
}

/// Reports the error of a check, if any, and returns whether the check passed
fn report(result: SemanticResult) -> bool {
    match result {
        Ok(()) => true,
        Err(err) => {
            err.emit();
            false
        }
    }
}

fn analyze_type<N: AstNode>(a: &mut Analysis, node: &N) {
    let Some(s) = a.get_symbol(node) else {
        return;
    };
    let name = a.get_qualified_name(&s);
    let id = s.node();
    if let Some(checker) = lookup(TYPES, &name) {
        // A type that is unknown has had its error reported
        if !a.type_map.contains_key(&id) {
            return;
        }
        let checked = report(checker(a, &name, id));
        let qualified = check_module_qualifiers(a, &s);
        if checked && qualified {
            a.framework_definitions.add_type(name, s);
        }
    }
}

/// Checks that the qualifiers of a framework definition are all modules,
/// reporting the first one that is not, and returns whether they are
fn check_module_qualifiers(a: &Analysis, symbol: &Symbol) -> bool {
    let mut current = symbol;
    while let Some(parent) = a.parent_symbol_map.get(current) {
        if !matches!(parent, Symbol::Module(_)) {
            let error = SemanticError::InvalidQualifier {
                loc: symbol.get_loc(),
                msg: format!(
                    "invalid qualifier {}: not a module symbol",
                    a.get_qualified_name(parent)
                ),
                def_loc: parent.get_loc(),
                def_msg: "symbol is defined here".to_string(),
            };
            Diagnostic::from(error)
                .note(format!(
                    "framework definition {} must have module qualifiers",
                    a.get_qualified_name(symbol)
                ))
                .emit();
            return false;
        }
        current = parent;
    }
    true
}

fn require_enum(a: &Analysis, name: &str, id: fpp_core::Node) -> SemanticResult {
    match a.type_map[&id].deref() {
        Type::Enum(_) => Ok(()),
        _ => Err(SemanticError::InvalidType {
            loc: id.span(),
            msg: format!("the F Prime framework type {} must be an enum", name),
            notes: vec![],
        }),
    }
}

fn require_integer_constant(a: &Analysis, name: &str, id: fpp_core::Node) -> SemanticResult {
    if Type::underlying_type(&a.type_map[&id]).is_int() {
        Ok(())
    } else {
        Err(SemanticError::InvalidType {
            loc: id.span(),
            msg: format!(
                "the F Prime framework constant {} must have an integer type",
                name
            ),
            notes: vec![],
        })
    }
}

fn require_integer_type_alias(a: &Analysis, name: &str, id: fpp_core::Node) -> SemanticResult {
    if Type::underlying_type(&a.type_map[&id]).is_int() {
        Ok(())
    } else {
        Err(SemanticError::InvalidType {
            loc: id.span(),
            msg: format!(
                "the F Prime framework type {} must be an alias of an integer type",
                name
            ),
            notes: vec![],
        })
    }
}

/// Whether the underlying type of the type at `id` is a primitive integer type
/// of the given signedness
fn has_signedness(a: &Analysis, id: fpp_core::Node, signedness: Signedness) -> bool {
    match Type::underlying_type(&a.type_map[&id]).deref() {
        Type::PrimitiveInt(kind) => kind.signedness() == signedness,
        _ => false,
    }
}

fn require_signed_integer_type_alias(
    a: &Analysis,
    name: &str,
    id: fpp_core::Node,
) -> SemanticResult {
    if has_signedness(a, id, Signedness::Signed) {
        Ok(())
    } else {
        Err(SemanticError::InvalidType {
            loc: id.span(),
            msg: format!(
                "the F Prime framework type {} must be an alias of a signed integer type",
                name
            ),
            notes: vec![],
        })
    }
}

fn require_unsigned_integer_type_alias(
    a: &Analysis,
    name: &str,
    id: fpp_core::Node,
) -> SemanticResult {
    if has_signedness(a, id, Signedness::Unsigned) {
        Ok(())
    } else {
        Err(SemanticError::InvalidType {
            loc: id.span(),
            msg: format!(
                "the F Prime framework type {} must be an alias of an unsigned integer type",
                name
            ),
            notes: vec![],
        })
    }
}
