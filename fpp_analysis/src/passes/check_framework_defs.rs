/// Check F Prime framework definitions
///
/// Framework definitions are module and component members, so this pass visits
/// translation unit, module and component members and the members of template
/// expansions.
pub struct CheckFrameworkDefs;

impl<'ast> Visitor<'ast> for CheckFrameworkDefs {
    type Break = ();
    type State = Analysis;

    fn super_visit(&self, a: &mut Analysis, node: Node<'ast>) -> ControlFlow<Self::Break> {
        node.walk(a, self)
    }

    /// The members generated by a template expansion are members of the
    /// enclosing module, so analyze them here.
    fn visit_spec_template_expand(
        &self,
        a: &mut Self::State,
        node: &'ast SpecTemplateExpand,
    ) -> ControlFlow<Self::Break> {
        visit_expansion(self, a, node)
    }

    /// The body of a module template is analyzed where the template is expanded,
    /// not at the point of the definition.
    fn visit_def_module_template(
        &self,
        _a: &mut Self::State,
        _node: &'ast DefModuleTemplate,
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// The members of a state machine are not framework definitions.
    fn visit_def_state_machine(
        &self,
        _a: &mut Self::State,
        _node: &'ast DefStateMachine,
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    fn visit_def_abs_type(
        &self,
        a: &mut Self::State,
        node: &'ast DefAbsType,
    ) -> ControlFlow<Self::Break> {
        analyze_type(a, node);
        ControlFlow::Continue(())
    }

    fn visit_def_alias_type(
        &self,
        a: &mut Self::State,
        node: &'ast DefAliasType,
    ) -> ControlFlow<Self::Break> {
        analyze_type(a, node);
        ControlFlow::Continue(())
    }

    fn visit_def_array(
        &self,
        a: &mut Self::State,
        node: &'ast DefArray,
    ) -> ControlFlow<Self::Break> {
        analyze_type(a, node);
        ControlFlow::Continue(())
    }

    fn visit_def_constant(
        &self,
        a: &mut Self::State,
        node: &'ast DefConstant,
    ) -> ControlFlow<Self::Break> {
        let Some(s) = a.get_symbol(node) else {
            return ControlFlow::Continue(());
        };
        let name = a.get_qualified_name(&s);
        if let Some(checker) = lookup(CONSTANTS, &name) {
            // A constant whose type is unknown has had its error reported
            let checked = match a.type_map.get(&node.node_id) {
                Some(_) => report(checker(a, &name, node.node_id)),
                None => false,
            };
            let qualified = check_module_qualifiers(a, &s);
            if checked && qualified {
                a.framework_definitions.add_constant(name, s);
            }
        }
        ControlFlow::Continue(())
    }

    fn visit_def_enum(&self, a: &mut Self::State, node: &'ast DefEnum) -> ControlFlow<Self::Break> {
        analyze_type(a, node);
        ControlFlow::Continue(())
    }

    fn visit_def_struct(
        &self,
        a: &mut Self::State,
        node: &'ast DefStruct,
    ) -> ControlFlow<Self::Break> {
        analyze_type(a, node);
        ControlFlow::Continue(())
    }
}

