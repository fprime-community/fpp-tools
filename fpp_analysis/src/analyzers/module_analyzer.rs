use crate::Analysis;
use crate::analyzers::analyzer::{Analyzer, DefaultAnalyzer};
use fpp_ast::{Node, SpecTemplateExpand, Visitable, Visitor};
use std::ops::ControlFlow;

/// Visit translation unit members and module members
#[derive(Default)]
pub struct ModuleAnalyzer<A = DefaultAnalyzer> {
    super_: A,
}

impl ModuleAnalyzer {
    pub fn new() -> ModuleAnalyzer {
        ModuleAnalyzer::default()
    }
}

impl<'ast, V, A> Analyzer<'ast, V> for ModuleAnalyzer<A>
where
    V: Visitor<'ast, State = Analysis>,
    A: Analyzer<'ast, V>,
{
    fn visit(&self, visitor: &V, a: &mut Analysis, node: Node<'ast>) -> ControlFlow<V::Break> {
        match node {
            Node::DefModule(def) => {
                a.scope_name_list.insert(0, def.name.data.clone());
                let result = def.members.visit(a, visitor);
                a.scope_name_list.remove(0);
                result
            }
            Node::SpecTemplateExpand(def) => visit_expansion(visitor, a, def),
            _ => self.super_.visit(visitor, a, node),
        }
    }
}

/// Visit the members generated by a template expansion specifier.
///
/// The members of an expansion are members of the enclosing module, so no scope
/// is pushed. The expansion is recorded for the duration of the visit, so that
/// names inside it resolve against the definitions the expansion introduced
/// rather than same-named definitions at the expansion site.
///
/// This is the analysis of a template expansion specifier by
/// [`ModuleAnalyzer`]. A pass that visits module members without a
/// [`ModuleAnalyzer`] calls it from [`Visitor::visit_spec_template_expand`].
pub fn visit_expansion<'ast, V>(
    visitor: &V,
    a: &mut Analysis,
    node: &'ast SpecTemplateExpand,
) -> ControlFlow<V::Break>
where
    V: Visitor<'ast, State = Analysis>,
{
    // Check if this template has been expanded
    let Some(members) = &node.members else {
        return ControlFlow::Continue(());
    };
    // Mark the analysis with the proper expansion
    let saved = a.template_expansion.replace(node.node_id);
    let out = members.visit(a, visitor);
    a.template_expansion = saved;
    out
}
