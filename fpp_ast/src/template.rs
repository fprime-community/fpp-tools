use crate::*;

/// Constant template parameter
#[ast]
#[derive(AstAnnotated, Clone, Replicate, VisitorWalkable, serde::Serialize)]
pub struct TemplateParamConstant {
    pub name: Name,
    pub type_name: TypeName,
}

/// Type template parameter
#[ast]
#[derive(AstAnnotated, Clone, Replicate, VisitorWalkable, serde::Serialize)]
pub struct TemplateParamType {
    pub name: Name,
}

/// Port interface instance template parameter
#[ast]
#[derive(AstAnnotated, Clone, Replicate, VisitorWalkable, serde::Serialize)]
pub struct TemplateParamInterface {
    pub name: Name,
    pub interface: QualIdent,
}

/// Template parameter
#[ast]
#[derive(AstAnnotated, Clone, Replicate, DirectWalkable, serde::Serialize)]
pub enum TemplateParam {
    Constant(TemplateParamConstant),
    Type(TemplateParamType),
    Interface(TemplateParamInterface),
}

impl TemplateParam {
    /// The name bound by this parameter
    pub fn name(&self) -> &Name {
        match self {
            TemplateParam::Constant(p) => &p.name,
            TemplateParam::Type(p) => &p.name,
            TemplateParam::Interface(p) => &p.name,
        }
    }

    /// The kind of this parameter, as it is spelled in FPP source
    pub fn kind_str(&self) -> &'static str {
        match self {
            TemplateParam::Constant(_) => "constant",
            TemplateParam::Type(_) => "type",
            TemplateParam::Interface(_) => "instance",
        }
    }
}

/// Template parameter list
pub type TemplateParamList = Vec<TemplateParam>;

/// The kinds of template argument
#[derive(Debug, Clone, Replicate, DirectWalkable, serde::Serialize)]
pub enum TemplateArgKind {
    Constant(Expr),
    Type(TypeName),
    Interface(QualIdent),
}

/// Template argument
#[ast]
#[derive(Debug, Clone, Replicate, VisitorWalkable, serde::Serialize)]
pub struct TemplateArg {
    pub kind: TemplateArgKind,
}

impl TemplateArg {
    /// The kind of this argument, as it is spelled in FPP source
    pub fn kind_str(&self) -> &'static str {
        match self.kind {
            TemplateArgKind::Constant(_) => "constant",
            TemplateArgKind::Type(_) => "type",
            TemplateArgKind::Interface(_) => "instance",
        }
    }
}

/// Template argument list
pub type TemplateArgList = Vec<TemplateArg>;

/// Module template definition
#[ast]
#[derive(AstAnnotated, Clone, Replicate, VisitorWalkable, serde::Serialize)]
pub struct DefModuleTemplate {
    pub name: Name,
    pub params: TemplateParamList,
    pub members: Vec<ModuleMember>,
}

/// Template expansion specifier
#[ast]
#[derive(AstAnnotated, Clone, Replicate, VisitorWalkable, serde::Serialize)]
pub struct SpecTemplateExpand {
    pub template: QualIdent,
    pub args: TemplateArgList,
    /// The members generated by expanding the template, present after template
    /// expansion has run
    pub members: Option<Vec<ModuleMember>>,
}
